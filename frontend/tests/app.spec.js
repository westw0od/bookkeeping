test("failed save remains visible and never writes a local ledger", async ({ page }) => {
  const username = `failure_${Date.now()}`;
  await page.goto("/#/login");
  await page.evaluate(() => localStorage.setItem("smart-ledger-transactions", JSON.stringify([{ amount: 99999, note: "旧版未归属账单" }])));
  await page.reload();
  await page.getByRole("button", { name: "注册", exact: true }).click();
  await page.getByLabel("用户名", { exact: true }).fill(username);
  await page.getByLabel("密码", { exact: true }).fill("browser-test-password-12345");
  await page.getByLabel("确认密码", { exact: true }).fill("browser-test-password-12345");
  await page.getByRole("button", { name: "创建账号" }).click();
  await expect(page.getByRole("heading", { name: "API Key 管理" })).toBeVisible();
  await page.getByRole("link", { name: "返回账本", exact: true }).click();
  await page.getByRole("link", { name: /查看今日支出/ }).click();
  await page.getByRole("button", { name: /饮食/ }).getByText("记一笔", { exact: true }).click();
  await page.getByLabel("金额", { exact: true }).fill("5.00");
  await page.route("**/api/ledger", route => route.request().method() === "POST" ? route.abort() : route.continue());
  await page.getByRole("button", { name: "确认", exact: true }).click();
  await expect(page.locator(".modal-card .error-text")).toContainText("未确认保存");
  await expect(page.locator(".modal-mask")).toBeVisible();
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem("smart-ledger-transactions")))).toEqual([{ amount: 99999, note: "旧版未归属账单" }]);
});
